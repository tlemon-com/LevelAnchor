#pragma once

#include <cstdint>

/*
    LedFont5x7 -- tiny 5x7 dot-matrix glyph table for the PixelScreen readouts.
    Header-only, static data. Sibling of ui/PixelScreen.h (its only consumer).

    Each glyph is 7 rows of 5-bit masks, bit 4 = leftmost pixel. Only the
    characters the readouts actually need are defined: digits, "+-.:~ ",
    "dB", the "LUFS" unit suffix, and the lowercase letters used by the
    warmup states. getGlyph() returns nullptr for anything else.

    The alphabet is deliberately partial. Add glyphs here before using any new
    character in a readout, or it will render as a blank cell (textWidthCells
    still counts it, so centring stays correct).
*/
namespace LedFont5x7
{
    constexpr int kWidth   = 5;
    constexpr int kHeight  = 7;
    constexpr int kAdvance = 6; // glyph width + 1 column spacing

    struct Glyph
    {
        char    ch;
        uint8_t row[7];
    };

    inline const Glyph* getGlyph(char c)
    {
        static const Glyph glyphs[] =
        {
            { '0', { 0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E } },
            { '1', { 0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E } },
            { '2', { 0x0E, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1F } },
            { '3', { 0x1F, 0x02, 0x04, 0x02, 0x01, 0x11, 0x0E } },
            { '4', { 0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02 } },
            { '5', { 0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E } },
            { '6', { 0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E } },
            { '7', { 0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08 } },
            { '8', { 0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E } },
            { '9', { 0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C } },
            { '+', { 0x00, 0x04, 0x04, 0x1F, 0x04, 0x04, 0x00 } },
            { '-', { 0x00, 0x00, 0x00, 0x1F, 0x00, 0x00, 0x00 } },
            { '.', { 0x00, 0x00, 0x00, 0x00, 0x00, 0x0C, 0x0C } },
            { ' ', { 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00 } },
            { 'd', { 0x01, 0x01, 0x0D, 0x13, 0x11, 0x13, 0x0D } },
            { 'B', { 0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E } },
            { '~', { 0x00, 0x00, 0x08, 0x15, 0x02, 0x00, 0x00 } },
            // Unit suffix "LUFS" and the timer separator.
            { 'L', { 0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F } },
            { 'U', { 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E } },
            { 'F', { 0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10 } },
            { 'S', { 0x0F, 0x10, 0x10, 0x0E, 0x01, 0x01, 0x1E } },
            { ':', { 0x00, 0x0C, 0x0C, 0x00, 0x0C, 0x0C, 0x00 } },
            // Lowercase set for the status messages ("warmup N", "ready").
            { 'a', { 0x00, 0x00, 0x0E, 0x01, 0x0F, 0x11, 0x0F } },
            { 'e', { 0x00, 0x00, 0x0E, 0x11, 0x1F, 0x10, 0x0E } },
            { 'm', { 0x00, 0x00, 0x1A, 0x15, 0x15, 0x15, 0x15 } },
            { 'p', { 0x00, 0x00, 0x1E, 0x11, 0x1E, 0x10, 0x10 } },
            { 'r', { 0x00, 0x00, 0x16, 0x19, 0x10, 0x10, 0x10 } },
            { 'u', { 0x00, 0x00, 0x11, 0x11, 0x11, 0x13, 0x0D } },
            { 'w', { 0x00, 0x00, 0x11, 0x11, 0x15, 0x15, 0x0A } },
            { 'y', { 0x00, 0x00, 0x11, 0x11, 0x0F, 0x01, 0x0E } },
        };

        for (const auto& g : glyphs)
            if (g.ch == c)
                return &g;
        return nullptr;
    }

    /** Pixel-cell width of a rendered string (no trailing spacing column). */
    inline int textWidthCells(const char* text)
    {
        int n = 0;
        for (const char* p = text; *p != 0; ++p)
            ++n;
        return n > 0 ? n * kAdvance - 1 : 0;
    }
}
